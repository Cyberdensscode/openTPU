"""Accuracy of weight quantization formats (opentpu/quant.py) on the real checkpoints.

    python3 tools/quant_eval.py [--model qwen3|lfm2|qwen35] [--configs NAME ...]
                                [--a8 mx|block|off] [--gen 40] [--json out.json] [--threads 8]
    python3 tools/quant_eval.py --report out.json ...     (markdown tables of saved results)

Runs the Hugging Face model in fp32 (PyTorch, CPU) with every matmul weight that openTPU streams
through the MXU (each nn.Linear of the decoder with K % 128 == 0, and the LM head; embeddings stay
fp32, they are gathered on the host) replaced by its quantize-dequantized copy (opentpu/quant.py
quantize: the survey's formats, and mx-int8 / mx-int4 / mx-fp4 / mx-nvfp4, the MX MXU's). With
A8 every such matmul's input is also fake-quantized to int8 as QACT does on the device: --a8 mx
(the default) the MX MXU's, a scale per row and a power-of-two offset per 32 (a8x32, the whole
input row one range); --a8 block the MXU's before MX, a scale per 128 (the survey's numbers in
docs/quant.md); --a8 off (or --no-a8) none. The reference is the unquantized fp32 model.

Metrics, all against the fp32 reference:
  wErr    relative squared weight error sum ||W - Q(W)||^2 / sum ||W||^2 over the quantized mats
  bits    bits per streamed weight (elements + block scales), MB the weight bytes per token
  ppl     perplexity on two small texts: tools/data/austen_pp_ch1.txt (the opening of Pride and
          Prejudice, public domain) and the prose of docs/isa.md (less likely to be memorized)
  KL      mean KL(ref || quant) of the next-token distributions over all evaluated positions
  top1    next-token argmax agreement: on the texts (teacher forced), and on greedy
          continuations of 8 prompts generated by the reference (`--gen` tokens each)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from opentpu import quant as Q  # noqa: E402

PROMPTS = ["A prime number larger than 100 is", "The capital of France is", "def fibonacci(n):",
           "Water boils at", "The quick brown fox",
           "In 1969, the first person to walk on the moon was",
           "The largest planet in the solar system is", "import numpy as np\n"]

# name -> (default format kwargs, {module-name regex: format kwargs} overrides; first match wins)
I8 = dict(fmt="int8")
CONFIGS = {
    "int8": (I8, {}),
    "int4-g128-fp32": (dict(fmt="int4", g=128, scale="fp32"), {}),
    "int4-g128-fp32-s": (dict(fmt="int4", g=128, scale="fp32", search=True), {}),
    "int4-g64-fp16": (dict(fmt="int4", g=64, scale="fp16"), {}),
    "int4-g32-fp16": (dict(fmt="int4", g=32, scale="fp16"), {}),
    "int4-g32-fp16-s": (dict(fmt="int4", g=32, scale="fp16", search=True), {}),
    "int4-g32-e8m0": (dict(fmt="int4", g=32, scale="e8m0"), {}),
    "int4-g32-e4m3": (dict(fmt="int4", g=32, scale="e4m3"), {}),
    "e2m1-g128-fp32": (dict(fmt="e2m1", g=128, scale="fp32"), {}),
    "e2m1-g128-fp32-s": (dict(fmt="e2m1", g=128, scale="fp32", search=True), {}),
    "mxfp4": (dict(fmt="mxfp4"), {}),
    "mxfp4-ceil": (dict(fmt="mxfp4", rule="ceil"), {}),
    "mxfp4-s": (dict(fmt="mxfp4", search=True), {}),
    "nvfp4": (dict(fmt="nvfp4"), {}),
    "nvfp4-s": (dict(fmt="nvfp4", search=True), {}),
    "int4k": (dict(fmt="int4k"), {}),
    "int4k-s": (dict(fmt="int4k", search=True), {}),
    "e2m1k": (dict(fmt="e2m1k"), {}),
    "e2m1k-s": (dict(fmt="e2m1k", search=True), {}),
    "mx-int8": (dict(fmt="mx-int8"), {}),
    "mx-int4": (dict(fmt="mx-int4"), {}),
    "mx-fp4": (dict(fmt="mx-fp4"), {}),
    "mx-nvfp4": (dict(fmt="mx-nvfp4"), {}),
}
# mixed 4/8 policies, built on a 4-bit format: LM head 8-bit; + first/last layer; + down_proj
MIXED = {"head8": {r"lm_head": I8},
         "ends8": {r"lm_head": I8, r"layers\.(0|LAST)\.": I8},
         "down8": {r"lm_head": I8, r"down_proj|mlp\.w2|feed_forward\.w2": I8},
         "attn8": {r"lm_head": I8, r"self_attn|linear_attn|\.conv\.|attention": I8}}
BASE_DEFAULT = ["int8", "int4-g128-fp32", "int4-g128-fp32-s", "int4-g64-fp16", "int4-g32-fp16",
                "int4-g32-fp16-s", "int4-g32-e8m0", "int4-g32-e4m3", "e2m1-g128-fp32",
                "e2m1-g128-fp32-s", "mxfp4", "mxfp4-ceil", "mxfp4-s", "nvfp4", "nvfp4-s",
                "int4k", "int4k-s", "e2m1k", "e2m1k-s",
                "mxfp4-s+head8", "nvfp4-s+head8", "int4k-s+head8", "e2m1k-s+head8",
                "e2m1k-s+ends8", "e2m1k-s+down8", "e2m1k-s+attn8",
                "mx-int8", "mx-fp4", "mx-nvfp4", "mx-fp4+head8", "mx-nvfp4+head8"]


def config(name: str):
    """A CONFIGS name, or '<base>+<mixed policy>' (e.g. mxfp4-s+head8; an mx- base's 8-bit
    weights are mx-int8)."""
    base, _, mix = name.partition("+")
    d, ov = CONFIGS[base]
    mixed = dict(MIXED[mix]) if mix else {}
    if base.startswith("mx-"):
        mixed = {k: CONFIGS["mx-int8"][0] if v is I8 else v for k, v in mixed.items()}
    return d, {**mixed, **ov}


def quant_targets(model) -> dict:
    """Module name -> nn.Linear for every matmul openTPU streams (K % 128 == 0), LM head too."""
    import torch
    out = {}
    for n, m in model.named_modules():
        if isinstance(m, torch.nn.Linear) and m.in_features % 128 == 0 and "visual" not in n \
                and "mtp" not in n:
            out[n] = m
    return out


def fake_q8(x, D: int = 128, mode: str = "mx"):
    """int8 fake quantization of a matmul input (QACT's numerics, float math): "mx" a scale
    per row (amax / 127) and a power-of-two offset per D/4, the largest (<= 31) that keeps the
    group's amax within the row's (quant.fake_act's); "block" a scale per D (before MX)."""
    import torch
    sh = x.shape
    if mode == "block":
        xb = x.reshape(*sh[:-1], sh[-1] // D, D)
        s = xb.abs().amax(-1, keepdim=True) / 127
        s = torch.where(s == 0, torch.ones_like(s), s)
        return (torch.clamp(torch.round(xb / s), -127, 127) * s).reshape(sh)
    g = D // Q.NSUB
    xd = x.double()
    xb = xd.reshape(*sh[:-1], sh[-1] // g, g)
    a = xd.abs().amax(-1, keepdim=True)                         # the row's amax
    ag = xb.abs().amax(-1)                                      # each group's
    fa, ea = torch.frexp(ag)
    fm, em = torch.frexp(a.expand_as(ag))
    d = torch.where(ag > 0, (em - ea - (fa > fm).int()).clamp(0, 31), torch.zeros_like(ea))
    s = torch.where(a == 0, torch.ones_like(a), a / 127)
    unit = (s * torch.exp2(-d.double()))[..., None]
    return (torch.clamp(torch.round(xb / unit), -127, 127) * unit).reshape(sh).to(x.dtype)


def report(paths) -> str:
    """Markdown tables (one per model) of results saved with --json."""
    out = []
    for p in paths:
        rows = json.loads(Path(p).read_text())
        ref = next(r for r in rows if "ref" in r)
        out += [f"**{ref['model']}** (fp32 reference: ppl {ref['ref']['ppl0']:.2f} / "
                f"{ref['ref']['ppl1']:.2f})", "",
                "| config | bits/w | MB | weight err | ppl book | ppl isa.md | KL | top-1 text | "
                "top-1 greedy |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for r in rows:
            if "ref" in r:
                continue
            out.append(f"| {r['config']} | {r['bits']:.2f} | {r['MB']:.0f} | {r['werr']:.4f} | "
                       f"{r['ppl0']:.2f} | {r['ppl1']:.2f} | {r['kl']:.3f} | "
                       f"{(r['top1_t0'] + r['top1_t1']) / 2:.3f} | {r['top1_gen']:.3f} |")
        out.append("")
    return "\n".join(out)


def main() -> None:
    if len(sys.argv) > 1 and sys.argv[1] == "--report":
        print(report(sys.argv[2:]))
        return
    import torch
    import transformers
    from opentpu.llm import model_dir

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--model", default="qwen3")
    ap.add_argument("--configs", nargs="*", default=BASE_DEFAULT)
    ap.add_argument("--a8", choices=["mx", "block", "off"], default="mx",
                    help="the matmul inputs' int8 quantization (mx: today's QACT)")
    ap.add_argument("--no-a8", action="store_true", help="weights only (--a8 off)")
    ap.add_argument("--gen", type=int, default=40, help="greedy tokens per prompt")
    ap.add_argument("--json", default=None, help="append results to this JSON file")
    ap.add_argument("--threads", type=int, default=8)
    a = ap.parse_args()
    if a.no_a8:
        a.a8 = "off"
    torch.set_grad_enabled(False)
    torch.set_num_threads(a.threads)

    path = model_dir(a.model)
    tok = transformers.AutoTokenizer.from_pretrained(path)
    model = transformers.AutoModelForCausalLM.from_pretrained(path, dtype=torch.float32).eval()
    targets = quant_targets(model)
    orig = {n: m.weight.detach().clone() for n, m in targets.items()}
    nlayers = 1 + max(int(x) for n in targets for x in re.findall(r"layers\.(\d+)\.", n))

    # evaluation sequences: two texts (ppl) and the reference's greedy continuations
    texts = [(ROOT / "tools/data/austen_pp_ch1.txt").read_text(),
             re.sub(r"`|\|", "", (ROOT / "docs/isa.md").read_text())]
    text_ids = [tok(t, return_tensors="pt").input_ids[:, :640] for t in texts]
    gen_ids = []
    for p in PROMPTS:
        ids = tok(p, return_tensors="pt").input_ids
        out = model.generate(ids, max_new_tokens=a.gen, do_sample=False,
                             pad_token_id=tok.eos_token_id)
        gen_ids.append((out, ids.shape[1]))

    a8 = {"on": a.a8 != "off"}
    hooks = [m.register_forward_pre_hook(
        lambda mod, inp: (fake_q8(inp[0], mode=a.a8),) if a8["on"] else None)
        for m in targets.values()]

    def run():
        """log-probs of every evaluated position: texts (all), greedy runs (generated part)."""
        lp_text = [torch.log_softmax(model(ids).logits[0, :-1].float(), -1) for ids in text_ids]
        lp_gen = [torch.log_softmax(model(o).logits[0, n0 - 1:-1].float(), -1) for o, n0 in gen_ids]
        return lp_text, lp_gen

    a8["on"] = False
    ref_text, ref_gen = run()
    a8["on"] = a.a8 != "off"

    def metrics(lp_text, lp_gen):
        r = {}
        for i, (lp, rl, ids) in enumerate(zip(lp_text, ref_text, text_ids)):
            nll = -lp.gather(1, ids[0, 1:, None]).mean().item()
            r[f"ppl{i}"] = float(np.exp(nll))
            r[f"top1_t{i}"] = (lp.argmax(-1) == rl.argmax(-1)).float().mean().item()
        allq = torch.cat(list(lp_text) + list(lp_gen))
        allr = torch.cat(list(ref_text) + list(ref_gen))
        r["kl"] = (allr.exp() * (allr - allq)).sum(-1).mean().item()
        r["top1_gen"] = torch.cat([(q.argmax(-1) == rr.argmax(-1)) for q, rr in
                                   zip(lp_gen, ref_gen)]).float().mean().item()
        return r

    ref = metrics(ref_text, ref_gen)
    print(f"# {a.model}: {len(targets)} matmuls, "
          f"{sum(w.numel() for w in orig.values()) / 1e6:.1f} M streamed weights, "
          f"A8={a.a8}; eval tokens: text {[t.shape[1] for t in text_ids]}"
          f", greedy {sum(o.shape[1] - n for o, n in gen_ids)}")
    print(f"# fp32 reference: ppl {ref['ppl0']:.3f} / {ref['ppl1']:.3f}")
    hdr = f"{'config':28s} {'bits':>5s} {'MB':>6s} {'wErr':>8s} {'ppl0':>7s} {'ppl1':>7s} " \
          f"{'KL':>7s} {'top1_t0':>7s} {'top1_t1':>7s} {'top1_g':>7s} {'s':>4s}"
    print(hdr)
    results = []
    for name in a.configs:
        t0 = time.time()
        d, ov = config(name)
        num = den = nbits = nw = 0.0
        for n, m in targets.items():
            kw = d
            for pat, k2 in ov.items():
                if re.search(pat.replace("LAST", str(nlayers - 1)), n):
                    kw = k2
                    break
            W = orig[n].numpy()
            q = Q.quantize(W, **kw)
            num += float(((q.deq.astype(np.float64) - W) ** 2).sum())
            den += float((W.astype(np.float64) ** 2).sum())
            nbits += q.bits * W.size
            nw += W.size
            m.weight = torch.nn.Parameter(torch.from_numpy(q.deq))
        r = metrics(*run())
        for n, m in targets.items():
            m.weight = torch.nn.Parameter(orig[n].clone())
        r.update(config=name, model=a.model, a8=a.a8, bits=nbits / nw,
                 MB=nbits / 8 / 1e6, werr=num / den)
        results.append(r)
        print(f"{name:28s} {r['bits']:5.2f} {r['MB']:6.1f} {r['werr']:8.5f} {r['ppl0']:7.3f} "
              f"{r['ppl1']:7.3f} {r['kl']:7.4f} {r['top1_t0']:7.3f} {r['top1_t1']:7.3f} "
              f"{r['top1_gen']:7.3f} {time.time() - t0:4.0f}", flush=True)
    for h in hooks:
        h.remove()
    if a.json:
        p = Path(a.json)
        old = json.loads(p.read_text()) if p.exists() else []
        p.write_text(json.dumps(old + [dict(ref=ref, model=a.model)] + results, indent=1))


if __name__ == "__main__":
    main()
